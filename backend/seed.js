const run = async () => {
  const uri = process.env.MONGODB_URI;
  if (!uri) {
    console.error('Set MONGODB_URI in backend/.env');
    process.exit(1);
  }

  await mongoose.connect(uri);

  await Vehicle.deleteMany({});
  await Vehicle.insertMany(vehicles);

  await VehicleAttribute.deleteMany({});
  await VehicleAttribute.insertMany(ATTRIBUTE_SEED);

  await Province.deleteMany({});
  await Province.insertMany(preparedProvinces);

  await Make.deleteMany({});
  await Make.insertMany(preparedMakes);

  await VehicleModel.deleteMany({});
  await VehicleModel.insertMany(preparedModels);

  await City.deleteMany({});
  await City.insertMany(preparedCities);

  const adminEmail = process.env.ADMIN_USERNAME || 'waseemsamra@gmail.com';
  await User.deleteOne({ username: adminEmail });
  const admin = new User({ username: adminEmail, email: adminEmail, role: 'admin' });
  admin.setPassword(process.env.ADMIN_PASSWORD || 'admin123');
  await admin.save();

  console.log(`Seeded ${vehicles.length} vehicles, ${ATTRIBUTE_SEED.length} attributes, ${preparedProvinces.length} provinces, ${preparedMakes.length} makes, ${preparedModels.length} models, ${preparedCities.length} cities; admin user: ${adminEmail}`);
  await mongoose.disconnect();
};

run().catch((e) => {
  console.error(e);
  process.exit(1);
});
