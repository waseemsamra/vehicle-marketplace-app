export const generateCityId = (cityName, index) => {
  const clean = (cityName || '').trim();
  if (!clean) return `CITY-${index}`;
  const prefix = clean
    .split(/\s+/)
    .map((w) => w[0])
    .join('')
    .slice(0, 3)
    .toUpperCase();
  const suffix = String(index + 1).padStart(3, '0');
  return `${prefix}-${suffix}`;
};

